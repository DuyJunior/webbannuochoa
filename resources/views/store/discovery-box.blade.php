<script>
document.addEventListener('DOMContentLoaded', function () {
    let currentSize = 3;
    let selectedSamples = []; // array of objects {id, name, brand, img}
    const sizeBtns = document.querySelectorAll('.size-btn');
    const boxSlots = document.getElementById('boxSlots');
    const priceDisplay = document.getElementById('boxPriceDisplay');
    const addBoxBtn = document.getElementById('addBoxBtn');
    const inputBoxSize = document.getElementById('inputBoxSize');
    const hiddenInputsWrap = document.getElementById('hiddenInputsWrap');

    function renderBox() {
        boxSlots.innerHTML = '';
        for (let i = 0; i < currentSize; i++) {
            const sample = selectedSamples[i];
            const slot = document.createElement('div');
            slot.className = 'box-slot' + (sample ? ' filled' : '');

            if (sample) {
                slot.innerHTML = `
                    <img src="${sample.img}" alt="${sample.name}" class="slot-filled-img">
                    <span class="slot-brand">${sample.brand}</span>
                    <strong class="slot-name">${sample.name}</strong>
                    <button type="button" class="remove-sample-btn" data-index="${i}">✕ Đổi mùi khác</button>
                `;
            } else {
                slot.innerHTML = `
                    <div class="slot-vial-icon">🧪</div>
                    <span class="slot-empty-text">+ Chọn mẫu ${i + 1}</span>
                    <span class="slot-empty-num">Khe thử mùi số ${i + 1}</span>
                `;
            }
            boxSlots.appendChild(slot);
        }

        // Update hidden inputs for form
        hiddenInputsWrap.innerHTML = '';
        selectedSamples.forEach(s => {
            const inp = document.createElement('input');
            inp.type = 'hidden';
            inp.name = 'perfume_ids[]';
            inp.value = s.id;
            hiddenInputsWrap.appendChild(inp);
        });

        // Update add to cart button
        if (selectedSamples.length === currentSize) {
            addBoxBtn.disabled = false;
            addBoxBtn.textContent = `Thêm Hộp ${currentSize} Mẫu Vào Giỏ Hàng (${currentSize === 5 ? '299.000₫' : '199.000₫'})`;
        } else {
            addBoxBtn.disabled = true;
            addBoxBtn.textContent = `Vui lòng chọn thêm ${currentSize - selectedSamples.length} mẫu nữa`;
        }

        // Highlight selected buttons in picker
        document.querySelectorAll('.select-sample-btn').forEach(b => {
            const id = parseInt(b.dataset.id);
            const isSel = selectedSamples.some(s => s.id === id);
            b.classList.toggle('selected', isSel);
            b.textContent = isSel ? '✓ Đã chọn vào hộp' : '+ Cho vào hộp';
        });
    }

    sizeBtns.forEach(btn => {
        btn.addEventListener('click', function () {
            sizeBtns.forEach(b => b.classList.remove('active'));
            this.classList.add('active');
            currentSize = parseInt(this.dataset.size);
            priceDisplay.textContent = parseInt(this.dataset.price).toLocaleString('vi-VN') + '₫';
            inputBoxSize.value = currentSize;
            if (selectedSamples.length > currentSize) {
                selectedSamples = selectedSamples.slice(0, currentSize);
            }
            renderBox();
        });
    });

    // Handle selecting perfume from catalog
    document.querySelectorAll('.select-sample-btn').forEach(btn => {
        btn.addEventListener('click', function () {
            const card = this.closest('.picker-card');
            const id = parseInt(card.dataset.id);
            const name = card.dataset.name;
            const brand = card.dataset.brand;
            const img = card.dataset.img;

            const existingIdx = selectedSamples.findIndex(s => s.id === id);
            if (existingIdx !== -1) {
                selectedSamples.splice(existingIdx, 1);
            } else {
                if (selectedSamples.length >= currentSize) {
                    alert(`Hộp hiện tại chứa tối đa ${currentSize} mẫu. Bạn hãy đổi một mẫu khác hoặc chọn gói Hộp 5 mẫu nhé!`);
                    return;
                }
                selectedSamples.push({ id, name, brand, img });
            }
            renderBox();
        });
    });

    // Handle removing sample from slot
    boxSlots.addEventListener('click', function (e) {
        if (e.target.classList.contains('remove-sample-btn')) {
            const idx = parseInt(e.target.dataset.index);
            selectedSamples.splice(idx, 1);
            renderBox();
        }
    });

    // Filter tabs
    document.querySelectorAll('.filter-tab').forEach(tab => {
        tab.addEventListener('click', function () {
            document.querySelectorAll('.filter-tab').forEach(t => t.classList.remove('active'));
            this.classList.add('active');
            const filter = this.dataset.filter;
            document.querySelectorAll('.picker-card').forEach(card => {
                if (filter === 'all' || card.dataset.gender === filter) {
                    card.style.display = 'flex';
                } else {
                    card.style.display = 'none';
                }
            });
        });
    });

    renderBox();
});
</script>
